type Rect = { x: number; y: number; w: number; h: number };

/* Renders a screenshot at natural size inside a layer scaled so the
   `focus` rect is centered & fully visible. Children in image px. */
function ScreenLayer({
  src,
  w,
  h,
  focus,
  children,
}: {
  src: string;
  w: number;
  h: number;
  focus: Rect;
  children?: React.ReactNode;
}) {
  const boxRef = useRef<HTMLDivElement>(null);
  const [dim, setDim] = useState({ w: 0, h: 0 });

  useEffect(() => {
    const el = boxRef.current;
    if (!el) return;
    const measure = () => setDim({ w: el.clientWidth, h: el.clientHeight });
    measure();
    const ro = new ResizeObserver(measure);
    ro.observe(el);
    return () => ro.disconnect();
  }, []);

  const s =
    dim.w && dim.h ? Math.min(dim.w / focus.w, dim.h / focus.h) : 1;
  const left = dim.w / 2 - (focus.x + focus.w / 2) * s;
  const top = dim.h / 2 - (focus.y + focus.h / 2) * s;

  return (
    <div ref={boxRef} className="absolute inset-0 overflow-hidden bg-[#f6f8fb]">
      {dim.h > 0 && (
        <div
          className="absolute"
          style={{
            left,
            top,
            width: w,
            height: h,
            transform: `scale(${s})`,
            transformOrigin: "0 0",
          }}
        >
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={src}
            alt=""
            aria-hidden="true"
            width={w}
            height={h}
            draggable={false}
            className="block h-full w-full"
            style={{ maxWidth: "none" }}
          />
          {children}
        </div>
      )}
    </div>
  );
}

